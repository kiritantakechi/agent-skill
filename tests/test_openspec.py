"""OpenSpec's generated instructions: one delivery, from one release.

`openspec update` writes the workflow skills under `.claude/skills/`
and, when its delivery includes commands, a second copy of the same
instructions under `.claude/commands/opsx/`. The repository delivers
them once, as skills, all generated by the release its design names.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLAUDE = ROOT / ".claude"
RELEASE = "1.16.0"
GENERATED_BY = re.compile(r'^\s*generatedBy:\s*"?([^"\s]+)"?\s*$', re.MULTILINE)


def test_every_openspec_skill_is_generated_by_one_release() -> None:
    skills = sorted(CLAUDE.glob("skills/openspec-*/SKILL.md"))
    assert skills
    versions = {
        path.parent.name: GENERATED_BY.findall(path.read_text()) for path in skills
    }
    assert versions == {name: [RELEASE] for name in versions}


def test_the_instructions_are_not_also_delivered_as_commands() -> None:
    assert not (CLAUDE / "commands" / "opsx").exists()
